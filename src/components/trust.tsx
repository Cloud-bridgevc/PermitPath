// Shared components that make provenance visible. Every place a requirement or
// regulatory statement is shown should use one of these, so verified information and
// AI suggestions are always visually distinct.

import type { Provenance, RegulatorySource, SourceSection } from "@/lib/types";
import { IconExternal, IconInfo, IconShield, IconSparkle } from "./icons";

export function VerifiedBadge({ label = "Verified source" }: { label?: string }) {
  return <span className="badge b-verified" title="Traceable to an approved official source and checked by a named reviewer"><IconShield />{label}</span>;
}

export function AiBadge({ label = "AI suggestion" }: { label?: string }) {
  return <span className="badge b-ai" title="Generated by AI or a heuristic. Not verified."><IconSparkle />{label}</span>;
}

export function FictionalBadge() {
  return <span className="badge b-fictional" title="Demonstration data: this jurisdiction and authority are invented">Fictional · demo</span>;
}

export function ProvenanceBadge({ p }: { p: Provenance }) {
  if (p.kind === "verified") return <VerifiedBadge />;
  if (p.groundingCheck === "quote_found") return <AiBadge label="AI suggestion · quote found" />;
  if (p.groundingCheck === "quote_not_found") return <span className="badge b-red" title="The quoted text does not appear in the source"><IconSparkle />AI suggestion · NOT in source</span>;
  return <AiBadge label="AI suggestion · no quote" />;
}

export function SourceCitation({
  source,
  section,
  quote,
  jurisdictionName,
  verifiedByName,
  ai = false,
}: {
  source: RegulatorySource;
  section?: SourceSection;
  quote?: string;
  jurisdictionName: string;
  verifiedByName?: string;
  ai?: boolean;
}) {
  return (
    <div className={"citation" + (ai ? " ai" : "")}>
      {quote && <blockquote>“{quote}”</blockquote>}
      <div className="meta">
        <span><b>{source.authority}</b></span>
        <span>{source.title}{section ? ` · ${section.heading}` : ""}</span>
        <span>Jurisdiction: <b>{jurisdictionName}</b></span>
        <span>Effective: <b>{source.effectiveDate}</b></span>
        <span>Last verified: <b>{source.lastVerifiedAt}</b>{verifiedByName ? ` by ${verifiedByName}` : ""}</span>
        {source.status !== "approved" && <span className="badge b-amber">{source.status.replace("_", " ")}</span>}
        {source.fictional && <span className="badge b-fictional">Fictional source</span>}
        <a href={source.url} target="_blank" rel="noreferrer" className="row" style={{ gap: 4 }}>Official source <IconExternal width={12} height={12} /></a>
      </div>
    </div>
  );
}

export function ConfirmWithAuthority({ authority }: { authority: string }) {
  return (
    <div className="callout callout-info">
      <IconInfo />
      <div>Confirm this requirement directly with <b>{authority}</b> before relying on it. PermitPath records what the source says; the authority decides how it applies.</div>
    </div>
  );
}

export function AiNotice({ children }: { children: React.ReactNode }) {
  return (
    <div className="callout callout-ai">
      <IconSparkle />
      <div>{children}</div>
    </div>
  );
}
